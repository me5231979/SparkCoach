// Spark extension build.
// 1. Validates the bundled processes (Phase 0: from fixtures/processes; Phase 2: downloaded from the Spark API).
// 2. Generates manifest.json: host permissions = exact hosts of those processes (no wildcards); CSP with one
//    connect-src origin (the Spark API) or none.
// 3. Bundles worker, content script and side panel with esbuild.
// 4. NETWORK GUARD: fails unless the bundles contain exactly the expected fetch call sites, all in src/lib/api.ts,
//    and no other network API, remote code, eval or externally_connectable.
// 5. PRIVACY GUARD: extension sources may not read DOM values or page text (that lives only in @spark/dom targeting).
import { build } from "esbuild";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../..");
const dist = join(here, process.env.SPARK_OUT || "dist");
const gen = join(here, "src/generated");
const pkg = JSON.parse(readFileSync(join(here, "package.json"), "utf8"));
const fail = (msg) => { console.error(`\n✖ BUILD FAILED: ${msg}\n`); process.exit(1); };

// The one origin the extension may talk to. Empty in Phase 0 (no network at all).
const API = (process.env.SPARK_API_ORIGIN || "").replace(/\/+$/, "");
if (API && !/^https:\/\/[a-z0-9.-]+$/.test(API) && !/^http:\/\/localhost:\d+$/.test(API)) fail("SPARK_API_ORIGIN must be an https origin with no path");
// Deliberate: update this when api.ts gains or loses a call site. Never bypass it.
const EXPECTED_FETCH = API ? 1 : 0;

// ── 1. Content ──────────────────────────────────────────────────────────────────────────────────────────────────
// Platform builds (SPARK_API_ORIGIN set) download each org's published coaches after sign-in: nothing is bundled.
// Offline builds (CI fixtures, demos) bundle validated processes from SPARK_PROCESSES.
const { validateProcess } = await import(join(root, "packages/core/src/validate.ts"));
const procDir = join(root, process.env.SPARK_PROCESSES || "fixtures/processes");
const processes = API ? [] : readdirSync(procDir).filter((f) => f.endsWith(".process.json")).sort().map((f) => {
  const data = JSON.parse(readFileSync(join(procDir, f), "utf8"));
  const r = validateProcess(data);
  if (!r.ok) fail(`${f} does not validate:\n  ${r.errors.join("\n  ")}`);
  return r.process;
});
if (!API && !processes.length) fail(`no processes in ${relative(root, procDir)}`);
// Extra hosts granted at install (test fixtures only). Real customers' systems are optional permissions.
const devHosts = (process.env.SPARK_DEV_HOSTS || "").split(",").map((s) => s.trim()).filter(Boolean);
const hosts = [...new Set([...processes.flatMap((p) => p.systems), ...devHosts])].sort();

mkdirSync(gen, { recursive: true });
writeFileSync(join(gen, "content.ts"), `// GENERATED by build.mjs. Do not edit.
export const VERSION = ${JSON.stringify(pkg.version)};
export const API_ORIGIN = ${JSON.stringify(API)};
export const PROCESSES: unknown[] = ${JSON.stringify(processes)};
`);

// ── 2. Manifest ─────────────────────────────────────────────────────────────────────────────────────────────────
const toPattern = (h) => {
  const host = h.split(":")[0];
  const local = host === "localhost" || /^127\./.test(host);
  return `${local ? "http" : "https"}://${h}/*`;
};
const hostPatterns = hosts.map(toPattern);
const manifest = {
  manifest_version: 3,
  name: "Spark",
  short_name: "Spark",
  version: pkg.version,
  description: "A coach beside your work: it teaches your company's processes in your own systems, and steps back as you learn.",
  minimum_chrome_version: "116",
  icons: { 16: "icons/16.png", 48: "icons/48.png", 128: "icons/128.png" },
  action: { default_title: "Open Spark" },
  side_panel: { default_path: "panel.html" },
  background: { service_worker: "background.js", type: "module" },
  ...(API
    ? {
        // Sign-in (identity), dynamic content scripts on the org's approved systems (scripting), periodic sync (alarms).
        permissions: ["storage", "sidePanel", "tabs", "identity", "scripting", "alarms"],
        host_permissions: [...new Set([`${API}/*`, ...hostPatterns])],
        optional_host_permissions: ["https://*/*", "http://localhost/*"],
      }
    : {
        permissions: ["storage", "sidePanel", "tabs"],
        host_permissions: hostPatterns,
        content_scripts: [{ matches: hostPatterns, js: ["content.js"], run_at: "document_idle", all_frames: true }],
      }),
  content_security_policy: { extension_pages: `script-src 'self'; object-src 'self'; connect-src ${API || "'none'"}` },
};
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, "manifest.json"), JSON.stringify(manifest, null, 2));

// ── 3. Bundles ──────────────────────────────────────────────────────────────────────────────────────────────────
// Offline builds swap the network module for a stub, so their bundles contain no network code at all.
const offlineApi = { name: "offline-api", setup(b) { if (API) return; b.onResolve({ filter: /\/lib\/api\.ts$/ }, (a) => ({ path: join(dirname(a.importer), a.path.replace(/api\.ts$/, "api-off.ts")) })); } };
const common = { plugins: [offlineApi], bundle: true, minify: true, target: "chrome116", legalComments: "none", logLevel: "warning", define: { "process.env.NODE_ENV": '"production"' } };
await build({ ...common, entryPoints: [join(here, "src/background.ts")], outfile: join(dist, "background.js"), format: "esm" });
await build({ ...common, entryPoints: [join(here, "src/content.ts")], outfile: join(dist, "content.js"), format: "iife" });
await build({ ...common, entryPoints: [join(here, "src/panel/main.tsx")], outdir: dist, entryNames: "panel", format: "iife", jsx: "automatic" });
cpSync(join(here, "src/panel/index.html"), join(dist, "panel.html"));

// Icons: a simple neutral mark, generated so the repo holds no binaries until the brand exists.
mkdirSync(join(dist, "icons"), { recursive: true });
for (const size of [16, 48, 128]) writeFileSync(join(dist, "icons", `${size}.png`), icon(size));

// ── 4. Network guard ────────────────────────────────────────────────────────────────────────────────────────────
const FORBIDDEN = [
  ["fetch(", /\bfetch\s*\(/], ["XMLHttpRequest", /\bXMLHttpRequest\b/], ["WebSocket", /\bWebSocket\b/],
  ["sendBeacon", /\bsendBeacon\b/], ["EventSource", /\bEventSource\b/], ["importScripts", /\bimportScripts\s*\(/],
  ["eval", /\beval\s*\(|new\s+Function\s*\(/],
  ["remote script/style/import", /(?:src|href)\s*=\s*["']?(?:https?:)?\/\/|import\s*\(\s*["'`]https?:|@import\s+(?:url\()?["']?https?:|url\(\s*["']?https?:/],
  ["externally_connectable", /externally_connectable/],
];
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const scannable = (p) => /\.(js|ts|tsx|css|html|json)$/.test(p) && !p.endsWith(".test.ts");
const API_FILE = join(here, "src/lib/api.ts");
const sources = [...walk(join(here, "src")), ...walk(join(root, "packages/core/src")), ...walk(join(root, "packages/dom/src"))].filter(scannable);
const hits = [];
for (const file of [...sources, ...walk(dist).filter(scannable)]) {
  const isBundle = file.startsWith(dist);
  readFileSync(file, "utf8").split("\n").forEach((line, i) => {
    for (const [name, re] of FORBIDDEN) {
      if (!re.test(line)) continue;
      if (name === "fetch(" && (file === API_FILE || (isBundle && EXPECTED_FETCH > 0 && file === join(dist, "background.js")))) continue;
      // React's bundle mentions `new Function` nowhere at runtime, but guard against false positives in minified code
      // only by name; anything else is a hit.
      hits.push(`${relative(root, file)}:${i + 1}  ${name}`);
    }
  });
}
if (hits.length) fail("network or remote-code API found outside src/lib/api.ts:\n  " + hits.join("\n  "));
const bundleFetches = ["background.js", "content.js", "panel.js"].reduce((n, f) => n + (readFileSync(join(dist, f), "utf8").match(/\bfetch\s*\(/g) ?? []).length, 0);
if (bundleFetches !== EXPECTED_FETCH) fail(`expected exactly ${EXPECTED_FETCH} fetch call site(s) in the bundles, found ${bundleFetches}`);
if (readFileSync(join(dist, "content.js"), "utf8").match(/\bfetch\s*\(/)) fail("the content script must never make network calls");
if (readFileSync(join(dist, "panel.js"), "utf8").match(/\bfetch\s*\(/)) fail("the side panel must never make network calls (it asks the worker)");
const urls = [...new Set(readFileSync(join(dist, "background.js"), "utf8").match(/https?:\/\/[a-z0-9.-]+(?::\d+)?/gi) ?? [])].filter((u) => !/w3\.org|reactjs\.org|react\.dev|json-schema\.org|x\.invalid/.test(u));
if (urls.some((u) => u !== API)) fail("unexpected address in the worker bundle: " + urls.filter((u) => u !== API).join(", "));

// ── 5. Privacy guard (extension sources) ────────────────────────────────────────────────────────────────────────
const DOM_READS = [/\.value\b/, /\binnerText\b/, /\btextContent\b(?!\s*=)/, /\bouterHTML\b/, /\binnerHTML\b/, /\bnodeValue\b/, /\bclipboard/i, /captureVisibleTab/, /desktopCapture/];
const priv = [];
for (const file of walk(join(here, "src")).filter((f) => /\.(ts|tsx)$/.test(f) && !f.includes("generated") && !f.endsWith(".test.ts"))) {
  if (file.includes(`${join("src", "panel")}`)) continue; // the panel renders its own UI; it never touches web pages
  readFileSync(file, "utf8").split("\n").forEach((line, i) => {
    if (line.trim().startsWith("//")) return;
    for (const re of DOM_READS) if (re.test(line)) priv.push(`${relative(root, file)}:${i + 1}  ${line.trim()}`);
  });
}
if (priv.length) fail("page-reading API used outside @spark/dom targeting:\n  " + priv.join("\n  "));

const size = (f) => (statSync(join(dist, f)).size / 1024).toFixed(0) + " kB";
console.log(`✔ Spark extension ${pkg.version} built → apps/extension/dist
  mode: ${API ? `platform → ${API}` : "offline (bundled processes)"}
  processes: ${processes.map((p) => p.id).join(", ") || "downloaded after sign-in"}
  host_permissions: ${hostPatterns.join(", ")}
  background.js ${size("background.js")} · content.js ${size("content.js")} · panel.js ${size("panel.js")}
  network guard: ${EXPECTED_FETCH ? `${EXPECTED_FETCH} call site(s), to ${API} only` : "no network code (connect-src 'none')"}
  privacy guard: clean`);

// ── helpers ─────────────────────────────────────────────────────────────────────────────────────────────────────
function icon(size) {
  const px = Buffer.alloc(size * (size * 4 + 1));
  const c = size / 2, r = size * 0.42;
  for (let y = 0; y < size; y++) {
    px[y * (size * 4 + 1)] = 0;
    for (let x = 0; x < size; x++) {
      const d = Math.hypot(x + 0.5 - c, y + 0.5 - c);
      const o = y * (size * 4 + 1) + 1 + x * 4;
      const inside = d <= r, spark = Math.abs(x + 0.5 - c) + Math.abs(y + 0.5 - c) < r * 0.62;
      px[o] = inside ? (spark ? 255 : 59) : 0; px[o + 1] = inside ? (spark ? 255 : 91) : 0; px[o + 2] = inside ? (spark ? 255 : 219) : 0; px[o + 3] = inside ? 255 : 0;
    }
  }
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(size, 0); ihdr.writeUInt32BE(size, 4); ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(px)), chunk("IEND", Buffer.alloc(0))]);
}
function crc32(buf) {
  let c, crc = 0xffffffff;
  for (const b of buf) { c = (crc ^ b) & 0xff; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; crc = (crc >>> 8) ^ c; }
  return (crc ^ 0xffffffff) >>> 0;
}
void existsSync;
